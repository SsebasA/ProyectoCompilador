from arpeggio import PTNodeVisitor
from collections import deque

class CodeGenerationVisitor(PTNodeVisitor):

    WAT_TEMPLATE = ''';; Code generated by the Delta compiler
(module
  (func
    (export "_start")
    (result i32)
{}  )
)
'''

    def __init__(self, symbol_table, **kwargs):
        super().__init__(**kwargs)
        self.__symbol_table = symbol_table

    def visit_program(self, node, children):

        def declare_variables():
            return ''.join([f'    (local ${var_name} i32\n)' for var_name in self.__symbol_table])
        

        return self.WAT_TEMPLATE.format(
            declare_variables()
            + ''.join(children)
            )
    
    def visit_statement(self, node, children):
        return children[0]
    
    def visit_declaration(self, node, children):
        return ''
    
    def visit_assignment(self, node, children):
        return children[1] + children[0]
    
    def visit_lhs_variable(self, node, children):
        name = node.value
        return f'    local.set ${name}\n'
    
    def visit_if(self, node, children):
        result = []
        count_ifs = 0
        result.append(children[0])
        result.append('    if\n')
        result.append(children[1])
        if len(children) == 3:
            result.append('    else\n')
            result.append(children[2])
        elif len(children) >= 4 and len(children) % 2 == 0:
            for i in range(2, len(children), 2):
                result.append('    else\n')
                result.append(children[i])
                result.append('    if\n')
                result.append(children[i + 1])
                count_ifs += 1
        elif len(children) >= 5 and len(children) % 2 != 0:
            for i in range(2, len(children) - 1, 2):
                result.append('    else\n')
                result.append(children[i])
                result.append('    if\n')
                result.append(children[i + 1])
                count_ifs += 1
            result.append('    else\n')
            result.append(children[-1])
        for c in range(count_ifs):
            result.append('    end\n')
        result.append('    end\n')
        return ''.join(result)

    def visit_block(self, node, children):
        return ''.join(children)
    
    def visit_while(self, node, children):
        result = []
        result.append('    block\n')
        result.append('    loop\n')
        result.append(children[0])
        result.append('    i32.eqz\n')
        result.append('    br_if 1\n')
        result.append(children[1])
        result.append('    br 0\n')
        result.append('    end\n')
        result.append('    end\n')

        return ''.join(result)
    
    def visit_do(self, node, children):
        result = []
        result.append('    loop\n')
        result.append(children[0])
        result.append(children[1])
        result.append('    br_if 0\n')
        result.append('    end\n')
        return ''.join(result)
    
    def visit_rhs_variable(self, node, children):
        name = node.value
        return f'    local.get ${name}\n'
    
    def visit_expression(self, node, children):
        if len(children) == 1:
            return children[0]
        result = [children[0]]
        for exp in children[1:]:
            result.append('    if (result i32)\n')
            result.append('    i32.const 1\n')
            result.append('    else\n')
            result.append(exp)
        result.append('    i32.eqz\n' * 2)
        result.append('    end\n' * (len(children) - 1))
        return ''.join(result)

        
    
    def visit_logical_and(self, node, children):
        if len(children) == 1:
            return children[0]
        result = [children[0]]
        for exp in children[1:]:
            result.append('    if (result i32)\n')
            result.append(exp)
        result.append('    i32.eqz\n' * 2)
        result.append(('    else\n'
                      '    i32.const 0\n'
                      '    end\n') * (len(children) - 1))
        return ''.join(result)




    def visit_additive(self, node, children):
        result = [children[0]]
        for i in range(1, len(children), 2):
            result.append(children[i + 1])
            match children[i]:
                case '+':
                    result.append('    i32.add\n')
                case '-':
                    result.append('    i32.sub\n')
        return ''.join(result)
    
    def visit_comparission(self, node, children):
        result = [children[0]]
        for i in range(1, len(children), 2):
            result.append(children[i + 1])
            match children[i]:
                case '>':
                    result.append('    i32.gt_s\n')
                case '<':
                    result.append('    i32.lt_s\n')
                case '==':
                    result.append('    i32.eq\n')
                case '>=':
                    result.append('    i32.ge_s\n')
                case '<=':
                    result.append('    i32.le_s\n')
                case '!=':
                    result.append('    i32.ne\n')
        return ''.join(result)
    
    def visit_multiplicative(self, node, children):
        result = [children[0]]
        for i in range(1, len(children), 2):
            result.append(children[i + 1])
            match children[i]:
                case '*':
                    result.append('    i32.mul\n')
                case '/':
                    result.append('    i32.div_s\n')
                case '%':
                    result.append('    i32.rem_s\n')
        return ''.join(result)

    def visit_primary(self, node, children):
        return children[0]
    
    def visit_binary(self, node, children):
        literal = node.value
        value = literal[2:]
        binary = int(value, 2)
        return f'    i32.const {binary}\n'

    
    def visit_octal(self, node, children):
        literal = node.value
        value = literal[2:]
        return f'    i32.const {int(value, 8)} \n'

    def visit_hex(self, node, children):
        literal = node.value
        value = literal[2:]
        return f'    i32.const {int(value, 16)}\n'


    def visit_boolean(self, node, children):
        if children[0] == 'true':
            return '    i32.const 1\n'
        return '    i32.const 0\n'

    def visit_decimal(self, node, children):
        return f'    i32.const {node.value}\n'
    
    def visit_parenthesis(self, node, children):
       return children[0]
    
    def visit_unary(self, node, children):
        result = deque()
        result.append(children[-1])
        for operator in children[-2::-1]:
            match operator:
                case '+':
                    ... #Do nothing 
                case '-':
                    result.appendleft('    i32.const 0\n')
                    result.append('    i32.sub\n')
                case '!':
                    result.append('    i32.eqz\n')
        
        return ''.join(list(result))
    
        

